/**
 * Single-file builds: bundles a lab — engine, presets and UI — into one
 * self-contained .jsx under standalone/, with only `react` and `react-dom`
 * left as imports. Handy for pasting into a Claude artifact, CodeSandbox or
 * any single-file playground. JSX is kept as JSX so the output stays readable.
 *
 *   npm run standalone
 *
 * The files it writes are generated: edit src/ and engine/, then re-run this.
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TARGETS = [
  {
    entry: "src/App.jsx",
    out: "standalone/StructuralLabApp.standalone.jsx",
    about: "The whole app: Beam, Frame, Truss and Arch labs plus the Practice tab (random exam-style questions, scratch pad, Beam Buddy).",
  },
  {
    entry: "src/BeamLab.jsx",
    out: "standalone/BeamLab.standalone.jsx",
    about: "Beam Lab: draggable supports, loads and hinges; SFD, BMD and deflection; narrated hand-solve; test-yourself quiz.",
  },
  {
    entry: "src/StructuralLab.jsx",
    out: "standalone/StructuralLab.standalone.jsx",
    about: "Frame / truss / arch lab: draggable nodes, loads and hinges; N, V, M and deflected shape; narrated checks; test-yourself quiz.",
  },
];

// One import block per file: "react" and "react-dom" both resolve to a single
// virtual module that imports them once and re-exports the bindings, so the
// bundle does not re-import React under a new alias for every source file.
const SHARED = [
  'import React, { useState, useEffect, useMemo, useRef } from "react";',
  'import { createPortal } from "react-dom";',
  "export { React as default, useState, useEffect, useMemo, useRef, createPortal };",
].join("\n");
const shared = {
  name: "shared-react",
  setup(b) {
    b.onResolve({ filter: /^react(-dom)?$/ }, a => (a.namespace === "shared" ? { path: a.path, external: true } : { path: "react", namespace: "shared" }));
    b.onLoad({ filter: /.*/, namespace: "shared" }, () => ({ contents: SHARED, loader: "js" }));
  },
};

const CONVENTIONS = [
  "Global X right +, Y up +, rotations and couples anticlockwise +.",
  "Axial N: tension +.  Bending M: sagging + (drawn on the tension face).",
  "Shear V: anticlockwise + (left face down, right face up), so V = -dM/dx.",
];

for (const t of TARGETS) {
  const result = await build({
    entryPoints: [resolve(root, t.entry)],
    bundle: true,
    write: false,
    format: "esm",
    jsx: "preserve",
    plugins: [shared],
    target: "es2020",
    charset: "utf8",
    legalComments: "none",
    logLevel: "warning",
  });
  const banner = [
    "/* ============================================================",
    `   STRUCTURAL LAB — ${t.out.replace("standalone/", "")}`,
    `   ${t.about}`,
    "",
    ...CONVENTIONS.map(c => `   ${c}`),
    "",
    `   GENERATED by \`npm run standalone\` from ${t.entry} and engine/.`,
    "   Edit those sources and re-run; do not edit this file by hand.",
    "   ============================================================ */",
    "",
  ].join("\n");
  writeFileSync(resolve(root, t.out), banner + result.outputFiles[0].text);
  console.log(`wrote ${t.out} (${(result.outputFiles[0].text.length / 1024).toFixed(0)} kB)`);
}
